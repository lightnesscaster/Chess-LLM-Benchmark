const assert = require('node:assert/strict');
const {AnalysisEngine} = require('../../web/static/js/analysis-engine.js');
const sent = [], updates = [];
const engine = new AnalysisEngine({postMessage: c => sent.push(c)}, info => updates.push(info));
engine.request({key: 'A', command: 'position startpos'});
assert.equal(sent.length, 0, 'wait for engine readiness');
engine.receive('readyok');
assert.deepEqual(sent, ['position startpos', 'go infinite']);
engine.receive('info depth 12 multipv 1 score cp 32 pv e2e4');
assert.equal(updates.length, 1);
engine.request({key: 'B', command: 'position startpos moves e2e4'});
engine.request({key: 'C', command: 'position startpos moves d2d4'});
assert.equal(sent.filter(c => c === 'stop').length, 1);
assert.equal(sent.filter(c => c === 'go infinite').length, 1, 'no overlapping searches');
engine.receive('info depth 1 multipv 1 score cp 0 pv a2a3');
assert.equal(updates.length, 1, 'ignore superseded info');
engine.receive('bestmove e2e4');
assert.deepEqual(sent.slice(-2), ['position startpos moves d2d4', 'go infinite']);
engine.receive('info depth 18 multipv 1 score cp 21 pv d7d5');
assert.equal(updates.at(-1).target.key, 'C');
engine.request({key: 'C', command: 'position startpos moves d2d4'});
assert.equal(sent.at(-1), 'go infinite', 'same position keeps its search depth');
engine.request({key: 'A', command: 'position startpos'});
engine.request({key: 'C', command: 'position startpos moves d2d4'});
engine.receive('info depth 1 score cp 0 pv d7d5');
assert.equal(updates.at(-1).depth, 18, 'stopped search cannot overwrite retained depth');
engine.receive('bestmove d7d5');
engine.receive('info depth 2 multipv 2 score cp 20 lowerbound pv g8f6');
assert.equal(updates.at(-1).depth, 18, 'bound scores are not exact evaluations');
engine.receive('info depth 22 multipv 1 score mate -3 pv d7d5');
assert.equal(updates.at(-1).mate, -3);
engine.stop();
engine.receive('info depth 23 score cp 0 pv d7d5');
assert.equal(updates.at(-1).depth, 22);
console.log('Analysis search lifecycle passed');
